const KEY = 'ownvoice.lang';
function detect() {
  try { const s = localStorage.getItem(KEY); if (s && D[s]) return s; } catch { /* приватний режим */ }
  const nav = (navigator.languages || [navigator.language || 'en']).map((l) => l.slice(0, 2).toLowerCase());
  return nav.find((l) => D[l]) || 'en';
}

export let lang = detect();

export function t(key, vars = {}) {
  const s = D[lang][key] ?? D.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}

export function setLang(l) {
  lang = D[l] ? l : 'en';
  try { localStorage.setItem(KEY, lang); } catch { /* приватний режим */ }
  applyStatic();
}

// Статичні тексти: data-i18n → textContent.
export function applyStatic() {
  document.documentElement.lang = lang;
  document.title = t('title');
  document.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
}
